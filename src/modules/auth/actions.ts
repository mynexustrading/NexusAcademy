'use server'

import { revalidatePath } from 'next/cache'
import { redirect } from 'next/navigation'
import { createClient } from '@/lib/supabase/server'
import { loginSchema, registerSchema } from './schemas'
import type { LoginFormData, RegisterFormData } from './schemas'

export async function signIn(data: LoginFormData): Promise<{ error: string }> {
  const parsed = loginSchema.safeParse(data)
  if (!parsed.success) {
    return { error: 'Invalid input. Please check your details.' }
  }

  const supabase = await createClient()
  const { error } = await supabase.auth.signInWithPassword({
    email: parsed.data.email,
    password: parsed.data.password,
  })

  if (error) {
    return { error: error.message }
  }

  revalidatePath('/', 'layout')
  redirect('/dashboard')
}

export async function signUp(data: RegisterFormData): Promise<{ error: string }> {
  const parsed = registerSchema.safeParse(data)
  if (!parsed.success) {
    return { error: 'Invalid input. Please check your details.' }
  }

  const supabase = await createClient()
  const { error } = await supabase.auth.signUp({
    email: parsed.data.email,
    password: parsed.data.password,
    options: {
      data: { name: parsed.data.name },
    },
  })

  if (error) {
    return { error: error.message }
  }

  revalidatePath('/', 'layout')
  redirect('/dashboard')
}

export async function signOut(): Promise<never> {
  const supabase = await createClient()
  await supabase.auth.signOut()
  revalidatePath('/', 'layout')
  redirect('/login')
}
